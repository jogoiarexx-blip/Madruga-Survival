import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import {SPIDER_GLB,SPIDER_CLIPS,verifySpiderClips,loadSpiderParts} from '../src/characters/spider-model.js';
import {spiderDecision,SPIDER_ATTACK_PHASE,SPIDER_WEB_PHASE,createSpiderAI} from '../src/gameplay/spider-ai.js';
const require=createRequire(import.meta.url);
const glb=readFileSync(new URL('../assets/models/aranha_sombria_animada.glb',import.meta.url));
assert.equal(glb.toString('utf8',0,4),'glTF');
assert.equal(glb.readUInt32LE(8),glb.length);
const jsonLength=glb.readUInt32LE(12),meta=JSON.parse(glb.toString('utf8',20,20+jsonLength));
assert.equal(meta.skins[0].joints.length,72);
assert.deepEqual(meta.animations.map(a=>a.name),SPIDER_CLIPS);
assert.ok(meta.meshes[0].primitives[0].attributes.JOINTS_0>=0);
assert.equal(meta.accessors[1].componentType,5120);
assert.equal(meta.accessors[4].normalized,true);
assert.equal(meta.images.length,3);
assert.ok(verifySpiderClips(meta.animations));
assert.ok(!verifySpiderClips([{name:'Idle'}]));
assert.equal(spiderDecision(1.7,true,0),'Attack');
assert.equal(spiderDecision(11,true,0),'WebShot');
assert.equal(spiderDecision(3,true,0,0.2),'Jump');
assert.equal(spiderDecision(20,true,0),null);
assert.equal(spiderDecision(1.5,false,0),null);
assert.equal(spiderDecision(1.5,true,5),null);
assert.ok(SPIDER_ATTACK_PHASE>.3&&SPIDER_ATTACK_PHASE<.5);
assert.ok(SPIDER_WEB_PHASE>.25&&SPIDER_WEB_PHASE<.5);
const events=[],enemy={type:'spider',mesh:{id:3,position:{x:1,y:0,z:1},rotation:{y:0,z:0},scale:{set(){} }},speed:3.5,damage:10,size:1.5,knockback:0,
 spiderVisual:{attacks:[],updateCalls:0,attack(clip){this.attacks.push(clip)},jump(){this.attacks.push('Jump')},update(){this.updateCalls++}}};
enemy.spiderBrain={cooldown:0,action:null,actionTime:0,hit:false};
const player={position:{x:1.5,y:0,z:1}};
const ai=createSpiderAI({player,getGroundHeight:()=>0,resolveCollision:(x,z)=>({x,z}),damagePlayer:()=>{events.push('hit');return true},throwProjectile:()=>events.push('web')});
ai.update(enemy,.1,0);
assert.equal(enemy.spiderBrain.action,'Attack');
for(let i=0;i<5;i++)ai.update(enemy,.1,i*.1);
assert.deepEqual(events,['hit']);
ai.update(enemy,.1,2);
assert.equal(events.length,1,'Mordida apenas uma vez por animação');
player.position.x=11;
enemy.spiderBrain.action=null;enemy.spiderBrain.cooldown=0;
ai.update(enemy,.1,5);
assert.equal(enemy.spiderBrain.action,'WebShot');
for(let i=0;i<6;i++)ai.update(enemy,.1,5+i*.1);
assert.equal(events.filter(e=>e==='web').length,1);
// O gerenciador não aceita um pacote de partes adulterado ou incompleto.
await assert.rejects(loadSpiderParts({GLTFLoader:class {},fetcher:async()=>({ok:true,json:async()=>({byteLength:100,parts:[]})})}),/inválido/);
const main=readFileSync(new URL('../src/main.js',import.meta.url),'utf8');
assert.match(main,/spiderModels\.preload/);
assert.match(main,/madrugaSpiderStatus/);
assert.match(main,/spiderModels\.updateCorpses/);
assert.match(main,/onWebHit:seconds/);
assert.match(main,/spiderAI,/);
assert.match(main,/spawnEnemy\('spider'\)/);
assert.match(main,/webSlowTimer>0\?\.52:1/);
console.log('v2.7: 22 verificações da Aranha Sombria aprovadas');
